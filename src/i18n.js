export const LANGS = { en, el };
let current = "en";

export function setLang(lang) { if (LANGS[lang]) current = lang; return current; }
export function getLang() { return current; }

/** Look up a string; call it with args when it is a function. Falls back to English, then to the key. */
export function t(key, ...args) {
  const v = LANGS[current][key] ?? en[key];
  if (v === undefined) return key;
  return typeof v === "function" ? v(...args) : v;
}
